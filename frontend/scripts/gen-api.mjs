#!/usr/bin/env node
// Generates the typed API client from the committed OpenAPI snapshot (frontend/openapi/openapi.json).
//
//   pnpm run gen-api                 -> src/api/generated/{schema.ts,client.ts}
//   node scripts/gen-api.mjs --out D --spec FILE
//
// The snapshot is written by the backend (scripts/refresh-openapi.sh, which runs the app with
// E9X_OPENAPI_ENABLED=true); OpenApiSnapshotIT fails when it is stale, ApiClientGen.test.ts when the generated
// client is. The output directory is emptied first, so removed endpoints disappear from the client.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const option = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? resolve(args[i + 1]) : fallback;
};
const spec = option('--spec', join(root, 'openapi', 'openapi.json'));
const out = option('--out', join(root, 'src', 'api', 'generated'));

const banner = '// GENERATED by scripts/gen-api.mjs from openapi/openapi.json. Do not edit; run `pnpm run gen-api`.\n';

const ast = await openapiTS(JSON.parse(readFileSync(spec, 'utf8')));
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'schema.ts'), `${banner}${astToString(ast)}`);
writeFileSync(
  join(out, 'client.ts'),
  `${banner}import createClient from 'openapi-fetch';
import type { paths } from './schema';

export type { components, paths } from './schema';

/** Typed fetch client for the English9x API. Every path, parameter, body and response comes from the OpenAPI spec. */
export function createApiClient(baseUrl = '') {
  return createClient<paths>({ baseUrl });
}
`,
);
console.log(`gen-api: ${readdirSync(out).map((f) => join(out, f)).join(', ')}`);
